CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha_hash VARCHAR(255),
    cpf_cnpj VARCHAR(255),
    data_nascimento DATE,
    perfil VARCHAR(255),
    criado_em TIMESTAMP(6)
);

CREATE TABLE plano (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    descricao VARCHAR(255),
    preco DOUBLE PRECISION,
    limite_dispositivos INTEGER
);

CREATE TABLE conteudo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    tipo VARCHAR(255),
    ano INTEGER,
    duracao_minutos INTEGER,
    relevancia DOUBLE PRECISION,
    sinopse TEXT,
    trailer_url VARCHAR(255),
    genero VARCHAR(255)
);

CREATE TABLE assinatura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT REFERENCES usuarios (id),
    plano_id BIGINT REFERENCES plano (id),
    data_inicio DATE,
    data_fim DATE,
    status VARCHAR(255)
);

CREATE TABLE favorito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT REFERENCES usuarios (id),
    conteudo_id BIGINT REFERENCES conteudo (id),
    adicionado_em TIMESTAMP(6)
);

CREATE TABLE historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios (id),
    conteudo_id BIGINT NOT NULL REFERENCES conteudo (id),
    assistido_em TIMESTAMP(6),
    progresso_segundos INTEGER,
    concluido BOOLEAN
);

CREATE TABLE metodo_pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT REFERENCES usuarios (id),
    tipo VARCHAR(255),
    tokenizado VARCHAR(255),
    principal BOOLEAN
);

CREATE TABLE filmes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(100) NOT NULL,
    sinopse TEXT,
    data_lancamento DATE,
    genero VARCHAR(50),
    duracao_minutos INTEGER,
    classificacao_indicativa VARCHAR(10)
);

CREATE TABLE funcionarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    cargo VARCHAR(255),
    cep VARCHAR(255),
    logradouro VARCHAR(255),
    bairro VARCHAR(255),
    localidade VARCHAR(255),
    uf VARCHAR(255)
);
